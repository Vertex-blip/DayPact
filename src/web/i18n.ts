export type TextKey = keyof typeof kk;
export const texts = (locale: Locale) => (locale === 'ru' ? ru : kk);
export function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem('daypact.locale');
    if (saved === 'kk' || saved === 'ru') return saved;
  } catch {
    /* private mode */
  }
  return navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'kk';
}
export function localDate(timeZone = 'Asia/Almaty', date = new Date()): string {
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(date);
  return ['year', 'month', 'day'].map((k) => parts.find((p) => p.type === k)?.value).join('-');
}
export function shiftDate(date: string, days: number): string {
  const d = new Date(`${date}T12:00:00Z`);
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}
