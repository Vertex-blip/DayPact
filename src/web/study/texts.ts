export function studyWeekNames(locale: Locale, short = false): string[] {
  return locale === 'ru'
    ? short
      ? ['Пн', 'Вт', 'Ср', 'Чт', 'Пт', 'Сб', 'Вс']
      : ['Понедельник', 'Вторник', 'Среда', 'Четверг', 'Пятница', 'Суббота', 'Воскресенье']
    : short
      ? ['Дс', 'Сс', 'Ср', 'Бс', 'Жм', 'Сб', 'Жс']
      : ['Дүйсенбі', 'Сейсенбі', 'Сәрсенбі', 'Бейсенбі', 'Жұма', 'Сенбі', 'Жексенбі'];
}
export function studyDateLabel(date: string, locale: Locale, year = false): string {
  const months =
    locale === 'ru'
      ? [
          'января',
          'февраля',
          'марта',
          'апреля',
          'мая',
          'июня',
          'июля',
          'августа',
          'сентября',
          'октября',
          'ноября',
          'декабря',
        ]
      : [
          'қаңтар',
          'ақпан',
          'наурыз',
          'сәуір',
          'мамыр',
          'маусым',
          'шілде',
          'тамыз',
          'қыркүйек',
          'қазан',
          'қараша',
          'желтоқсан',
        ];
  return `${Number(date.slice(8, 10))} ${months[Number(date.slice(5, 7)) - 1]}${year ? ` ${date.slice(0, 4)}` : ''}`;
}
